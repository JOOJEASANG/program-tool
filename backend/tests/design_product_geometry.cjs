const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const geometry=fs.readFileSync('js/design-product-geometry.js','utf8');
const choices={leafletPanelCenter:{value:'99.5'},leafletPanelRight:{value:'99.5'},
  leafletFoldType:{value:'roll-left'},invitationFoldType:{value:'folded'},invitationFoldPosition:{value:'143'}};
const doc={documentElement:{dataset:{designStudio:'leaflet'}},getElementById:id=>choices[id]||null};
const host={document:doc,location:{search:'?studio=leaflet&side=outside'},URLSearchParams,window:{}};
vm.runInNewContext(geometry,host,{filename:'design-product-geometry.js'});
const service=host.window.DesignProductGeometry,plain=v=>JSON.parse(JSON.stringify(v));
let spec={coverMode:'spread',trimW:98,trimH:210,spine:98,bleed:3,safe:8,wing:0,workW:300,workH:216};
let v=service.adapt(spec,'leaflet');
assert.deepEqual(plain(v.panelWidths),[98,99.5,99.5]);
assert.equal(v.workW,303);
assert.deepEqual(plain(v.folds),[101,200.5]);
assert.equal(v.panels[0].label,'접어 넣는 면');
assert.equal(v.panels[2].label,'표지');
assert.equal(service.warnings(v).length,0);
choices.leafletFoldType.value='roll-right';
spec={...spec,spine:98};
v=service.adapt(spec,'leaflet');
assert.equal(v.panels[0].label,'표지');
assert.ok(service.warnings(v).length>=1,'right inward panel must be narrower');
choices.leafletFoldType.value='accordion';
v=service.adapt({...spec},'leaflet');
assert.equal(v.foldType,'accordion');
assert.equal(v.folds.length,2);
doc.documentElement.dataset.designStudio='invitation';
const base={coverMode:'frontBack',trimW:148,trimH:210,spine:0,bleed:3,safe:8,wing:0,workW:302,workH:216};
let folded=service.adapt({...base},'invitation');
assert.deepEqual(plain(folded.panelWidths),[143,153]);
assert.equal(folded.folds[0],146);
assert.equal(folded.workW,302);
assert.match(service.summary(folded),/143\.0 \+ 153\.0/);
choices.invitationFoldPosition.value='120';
folded=service.adapt({...base},'invitation');
assert.deepEqual(plain(folded.panelWidths),[120,176]);
choices.invitationFoldType.value='flat';
const flat=service.adapt({...base},'invitation');
assert.equal(flat.folds.length,0);
assert.deepEqual(plain(flat.panelWidths),[148,148]);
doc.documentElement.dataset.designStudio='flyer';
const flyer=service.adapt({coverMode:'front',trimW:210,trimH:297,spine:0,bleed:3,safe:10,wing:0,workW:216,workH:303},'flyer');
assert.equal(flyer.panels.length,1);
assert.equal(flyer.panels[0].label,'전단지 앞면');
assert.equal(flyer.workW,216);
console.log('product geometry behavior passed');

const fs=require('fs');
const vm=require('vm');
const path=require('path');
const assert=require('assert').strict;
const code=fs.readFileSync(path.join(__dirname,'../../js/print-specialists/variable-multiup.js'),'utf8');
const state={window:{},document:{readyState:'loading',addEventListener(){}},console,setTimeout(){}};
vm.runInNewContext(code,state);
const plan=state.window.PrintMultiVariableLayout.grid;
assert.equal(typeof plan,'function');
const MM=72/25.4;
const a=plan(100,90*MM,50*MM,297*MM,420*MM,5,5);
assert.equal(a.cols,3);
assert.equal(a.rows,7);
assert.equal(a.per,21);
assert.equal(a.pages,5);
assert.equal(a.items(0).length,21);
assert.equal(a.items(4).length,16);
assert.deepEqual(Array.from(a.items(0).map(p=>p.index)),Array.from({length:21},(_,i)=>i));
assert.deepEqual(Array.from(a.items(4).map(p=>p.index)),Array.from({length:16},(_,i)=>i+84));
assert(Math.abs(a.left/MM-8.5)<.001);
assert(Math.abs(a.top/MM-20)<.001);
const positions=a.items(0);
assert(Math.abs(positions[1].x-positions[0].x-95*MM)<.001);
assert(Math.abs(positions[3].y-positions[0].y-55*MM)<.001);
assert(positions.every(p=>p.x>=5*MM&&p.y>=5*MM));
const b=plan(3,90*MM,50*MM,420*MM,297*MM,5,5);
assert.equal(b.cols,4);
assert.equal(b.rows,5);
assert.equal(b.per,20);
assert.equal(b.pages,1);
const c=plan(1,210*MM,297*MM,297*MM,420*MM,5,5);
assert.equal(c.per,1);
assert.throws(()=>plan(2,300*MM,50*MM,297*MM,420*MM,5,5),/들어가지 않습니다/);
assert.throws(()=>plan(101,210*MM,297*MM,210*MM,297*MM,5,5),/들어가지 않습니다/);
assert.throws(()=>plan(1,90*MM,50*MM,297*MM,420*MM,-1,5),/여백/);
assert.throws(()=>plan(1,90*MM,50*MM,297*MM,420*MM,5,0),/간격/);
assert.throws(()=>plan(1,90*MM,50*MM,297*MM,420*MM,5,NaN),/간격/);
const zero=plan(300,90*MM,50*MM,297*MM,420*MM,5,5);
assert.equal(zero.pages,15);
assert.equal(zero.items(14).length,6);
console.log('variable multi-up geometry and distinct Excel record placement passed');
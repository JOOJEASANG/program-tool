// Keeps the PDF editor's save action available and makes large result delivery resilient.
(function(){
  'use strict';
  if(window.__pdfOutputSaveRecoveryV1)return;
  window.__pdfOutputSaveRecoveryV1=true;

  const path=(location.pathname||'/').replace(/\/+$/,'')||'/';
  if(path!=='/pdf-editor'&&path!=='/pdf-editor/index.html'&&!path.endsWith('/pdf-editor/index.html'))return;

  const DOWNLOAD_URL_GRACE_MS=30000;
  const DIRECT_SAVE_ARM_MS=360000;
  const STORAGE_DOWNLOAD_PREFIX='https://firebasestorage.googleapis.com/';
  let previewObserver=null;
  let thumbObserver=null;
  let deliveryInstalled=false;
  let directIntentInstalled=false;
  let directSaveArmedUntil=0;
  let directSaveTimer=null;
  const directStorageUrls=new Set();

  const $=id=>document.getElementById(id);

  function stateReady(){
    try{
      return Array.isArray(uploadedFiles)
        && uploadedFiles.length>0
        && Array.isArray(parsedPages)
        && parsedPages.some(page=>!page?.excluded);
    }catch(_){
      return false;
    }
  }

  function operationBusy(){
    try{return !!window.PdfOperationManager?.active?.();}
    catch(_){return false;}
  }

  function previewIdle(){
    const preview=$('previewBtn');
    return !preview||preview.disabled===false;
  }

  function sync(){
    const direct=$('downloadBtn');
    const ready=stateReady();
    if(direct&&ready&&previewIdle()&&!operationBusy())direct.disabled=false;

    const check=$('pdfEditorFinalCheckBtn');
    if(check&&ready&&direct?.disabled===false&&!operationBusy())check.disabled=false;

    document.documentElement.dataset.pdfOutputSaveReady=ready?'1':'0';
    return ready;
  }

  function clearDirectSave(reason='idle'){
    directSaveArmedUntil=0;
    if(directSaveTimer){
      clearTimeout(directSaveTimer);
      directSaveTimer=null;
    }
    document.documentElement.dataset.pdfStorageDirectSave=reason;
  }

  function armDirectSave(){
    directSaveArmedUntil=Date.now()+DIRECT_SAVE_ARM_MS;
    if(directSaveTimer)clearTimeout(directSaveTimer);
    directSaveTimer=setTimeout(()=>clearDirectSave('expired'),DIRECT_SAVE_ARM_MS);
    document.documentElement.dataset.pdfStorageDirectSave='armed';
  }

  function directSaveArmed(){
    if(!directSaveArmedUntil)return false;
    if(Date.now()<=directSaveArmedUntil)return true;
    clearDirectSave('expired');
    return false;
  }

  function installDirectSaveIntent(){
    if(directIntentInstalled)return true;
    directIntentInstalled=true;
    document.addEventListener('click',event=>{
      const target=event.target?.closest?.('#downloadBtn,#pdfEditorFinalCheckBtn');
      if(!target)return;
      if(target.id==='downloadBtn')armDirectSave();
      else clearDirectSave('final-check');
    },true);
    document.addEventListener('change',event=>{
      if(event.target?.id==='fileInput')clearDirectSave('file-change');
    },true);
    return true;
  }

  // Direct PDF save does not need to pull a large Firebase Storage result back
  // through fetch() and buffer it in JavaScript memory. For the core direct-save
  // button only, preserve the Storage delivery contract and hand its HTTPS URL to
  // the browser's native download stack. Final-check/preflight flows still receive
  // a Blob because they need the generated bytes for inspection.
  function installStorageDirectBridge(){
    const nativeRead=window._readPdfDelivery;
    if(typeof nativeRead!=='function')return false;
    if(nativeRead.__pdfStorageDirectBridgeV1)return true;

    const bridgedRead=async function(resp,options={}){
      if(!directSaveArmed())return nativeRead.call(this,resp,options);
      const contentType=resp?.headers?.get?.('content-type')||'';
      if(!contentType.includes('application/json'))return nativeRead.call(this,resp,options);

      let delivery=null;
      try{delivery=await resp.clone().json();}
      catch(_){return nativeRead.call(this,resp,options);}

      const downloadUrl=String(delivery?.download_url||'');
      if(delivery?.delivery!=='storage'||!downloadUrl.startsWith(STORAGE_DOWNLOAD_PREFIX)){
        return nativeRead.call(this,resp,options);
      }

      document.documentElement.dataset.pdfStorageResultTransport='browser-direct-v1';
      return {
        __pdfStorageBrowserDeliveryV1:true,
        download_url:downloadUrl,
        filename:String(delivery.filename||'output.pdf'),
        storage_path:String(delivery.storage_path||''),
        expires_at:String(delivery.expires_at||''),
        size_bytes:Number(delivery.size_bytes||0),
      };
    };
    bridgedRead.__pdfStorageDirectBridgeV1=true;
    bridgedRead.__pdfStorageDirectNative=nativeRead;
    window._readPdfDelivery=bridgedRead;
    document.documentElement.dataset.pdfStorageDirectBridge='1';
    return true;
  }

  // The core editor normally creates a temporary blob URL and immediately
  // revokes it. Keep blob anchors mounted long enough for Chrome to accept the
  // download. When the large-save bridge returns a Storage delivery marker,
  // URL.createObjectURL is translated to the HTTPS download URL so the browser
  // streams the file directly to disk instead of fetch() buffering it again.
  function installResultDownloadDelivery(){
    if(deliveryInstalled)return true;
    if(!window.HTMLAnchorElement||!window.URL?.createObjectURL||!window.URL?.revokeObjectURL)return false;
    deliveryInstalled=true;

    const proto=window.HTMLAnchorElement.prototype;
    const nativeClick=proto.click;
    const nativeCreate=window.URL.createObjectURL.bind(window.URL);
    const nativeRevoke=window.URL.revokeObjectURL.bind(window.URL);
    const protectedUrls=new Set();
    const cleanupTimers=new Map();

    function scheduleRelease(url){
      if(!url||cleanupTimers.has(url))return;
      const timer=setTimeout(()=>{
        cleanupTimers.delete(url);
        protectedUrls.delete(url);
        try{nativeRevoke(url);}catch(_){}
      },DOWNLOAD_URL_GRACE_MS);
      cleanupTimers.set(url,timer);
    }

    if(!window.URL.createObjectURL.__pdfResultDownloadDeliveryV3){
      const guardedCreate=function(value){
        if(value?.__pdfStorageBrowserDeliveryV1&&value.download_url){
          const remote=String(value.download_url);
          directStorageUrls.add(remote);
          clearDirectSave('handoff');
          document.documentElement.dataset.pdfStorageResultObjectUrl='remote-v1';
          return remote;
        }
        return nativeCreate(value);
      };
      guardedCreate.__pdfResultDownloadDeliveryV3=true;
      guardedCreate.__pdfResultDownloadNative=nativeCreate;
      window.URL.createObjectURL=guardedCreate;
    }

    if(!nativeClick.__pdfResultDownloadDeliveryV3){
      const guardedClick=function(){
        const href=String(this.href||'');
        const isPdfBlob=Boolean(this.download)&&href.startsWith('blob:');
        const isStorageDirect=directStorageUrls.has(href);
        let mounted=false;

        if(isPdfBlob){
          protectedUrls.add(href);
          scheduleRelease(href);
          if(directSaveArmed())clearDirectSave('blob-result');
        }

        if(isPdfBlob||isStorageDirect){
          if(!this.isConnected&&document.body){
            this.style.display='none';
            this.dataset.pdfResultDownload=isStorageDirect?'storage-direct':'1';
            document.body.appendChild(this);
            mounted=true;
          }
          document.documentElement.dataset.pdfResultDownloadDispatch=isStorageDirect
            ?'mounted-storage-direct-v1'
            :'mounted-blob-v2';
        }
        try{
          return nativeClick.call(this);
        }finally{
          if(mounted)setTimeout(()=>{try{this.remove();}catch(_){}},1500);
        }
      };
      guardedClick.__pdfResultDownloadDeliveryV3=true;
      guardedClick.__pdfResultDownloadNative=nativeClick;
      proto.click=guardedClick;
    }

    if(!window.URL.revokeObjectURL.__pdfResultDownloadDeliveryV3){
      const guardedRevoke=function(url){
        const value=String(url||'');
        if(directStorageUrls.has(value)){
          setTimeout(()=>directStorageUrls.delete(value),DOWNLOAD_URL_GRACE_MS);
          return;
        }
        if(protectedUrls.has(value)){
          scheduleRelease(value);
          return;
        }
        return nativeRevoke(url);
      };
      guardedRevoke.__pdfResultDownloadDeliveryV3=true;
      guardedRevoke.__pdfResultDownloadNative=nativeRevoke;
      window.URL.revokeObjectURL=guardedRevoke;
    }

    document.documentElement.dataset.pdfResultDownloadDelivery='blob-grace-v3-storage-direct';
    return true;
  }

  function observe(){
    const preview=$('previewBtn');
    if(preview&&!previewObserver){
      previewObserver=new MutationObserver(()=>setTimeout(sync,0));
      previewObserver.observe(preview,{attributes:true,attributeFilter:['disabled']});
    }
    const thumbs=$('thumbArea');
    if(thumbs&&!thumbObserver){
      thumbObserver=new MutationObserver(()=>setTimeout(sync,0));
      thumbObserver.observe(thumbs,{childList:true});
    }
    return !!$('downloadBtn');
  }

  function install(attempt=0){
    installResultDownloadDelivery();
    installDirectSaveIntent();
    if(!installStorageDirectBridge()&&attempt<30){
      setTimeout(()=>installStorageDirectBridge(),100+attempt*20);
    }
    if(!observe()){
      if(attempt<30)setTimeout(()=>install(attempt+1),100+attempt*20);
      return false;
    }
    sync();
    [180,500,1200,2200].forEach(delay=>setTimeout(sync,delay));
    document.addEventListener('pdf-editor:pages-changed',()=>setTimeout(sync,0));
    document.documentElement.dataset.pdfOutputSaveRecovery='2';
    return true;
  }

  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',()=>install(0),{once:true});
  else install(0);

  window.PdfOutputSaveRecovery={
    sync,
    stateReady,
    installResultDownloadDelivery,
    installStorageDirectBridge,
    stage:'core-save-button-recovery-v3-storage-direct'
  };
})();
